// Writes promo/series.js for the promo video templates in promo/: every price series (with its latest
// value appended as a fractional year), the CPI and the daily schedule. Rerun after the price data changes.
//   node scripts/promo-data.mjs
import {readFileSync, writeFileSync} from "node:fs";
import {fileURLToPath} from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = f => JSON.parse(readFileSync(path.join(root, f), "utf8"));
const {series} = read("data/prices.json"), cpi = read("data/cpi.json"), {epoch, days} = read("data/schedule.json");
const SER = {};
for (const s of series) {
  const pts = s.pts ? s.pts.map(p => [p[0], p[1], p[2] || null, p[3] || null]) : s.v.map((v, i) => [s.start + i, v]).filter(p => p[1] != null);
  let now = null;
  if (s.latest) { const [y, m] = s.latest.period.split("-").map(Number); now = [y + (m - 1) / 12, s.latest.value, null, s.latest.period]; }
  SER[s.sym] = {name: s.name || s.line, line: s.line || null, unit: s.unit, loc: s.loc, cat: s.cat, who: s.who || null, src: s.src || null, jan: !s.pts,
    pts: now && now[0] > pts[pts.length - 1][0] ? [...pts, now] : pts};
}
writeFileSync(path.join(root, "promo/series.js"),
  "// Generated by scripts/promo-data.mjs from data/. Do not edit.\n" +
  "window.SER=" + JSON.stringify(SER) + ";\nwindow.CPI=" + JSON.stringify({start: cpi.start, v: cpi.v}) +
  ";\nwindow.SCHED=" + JSON.stringify({epoch, days}) + ";\n");
console.log("wrote promo/series.js:", Object.keys(SER).length, "series");
